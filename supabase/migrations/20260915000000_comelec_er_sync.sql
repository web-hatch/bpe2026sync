create table if not exists public.comelec_discovery_tasks (
  id bigint generated by default as identity primary key,
  task_key text not null unique,
  task_type text not null check (task_type in ('province', 'municipality', 'barangay')),
  province_code text not null,
  locality_code text,
  status text not null default 'pending' check (status in ('pending', 'processing', 'done', 'failed')),
  attempts integer not null default 0,
  locked_at timestamptz,
  completed_at timestamptz,
  next_attempt_at timestamptz not null default now(),
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.comelec_er_queue (
  precinct_id text primary key,
  province_code text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'ready', 'failed')),
  attempts integer not null default 0,
  locked_at timestamptz,
  last_checked_at timestamptz,
  last_downloaded_at timestamptz,
  next_check_at timestamptz not null default now(),
  content_hash text,
  storage_path text,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists comelec_er_queue_due_idx
  on public.comelec_er_queue (status, next_check_at);

create table if not exists public.comelec_er_records (
  precinct_id text primary key references public.comelec_er_queue (precinct_id) on delete cascade,
  content_hash text not null,
  source_url text not null,
  storage_path text not null,
  payload_bytes integer not null,
  fetched_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

